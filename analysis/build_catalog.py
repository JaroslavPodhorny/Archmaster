"""Builds analysis/02_katalog_uloh.md and summary tables from
data/m9_task_catalog.tsv (hand-classified from the official test booklets)
and data/m9_item_stats_2022_2026.csv (CERMAT aggregated item results)."""
import csv, collections, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
TAGS = {
    'N-ARIT': 'Číselné výrazy, mocniny, odmocniny',
    'N-ZLOM': 'Zlomky',
    'N-DEL': 'Dělitelnost, prvočísla',
    'N-JED': 'Převody jednotek, čas',
    'A-VYR': 'Úpravy výrazů, vzorce, vytýkání',
    'A-ROV': 'Lineární rovnice',
    'A-SOU': 'Soustava dvou rovnic',
    'A-SLOV': 'Výraz s proměnnou a slovní úloha na rovnici',
    'P-PROC': 'Procenta',
    'P-POM': 'Poměr, úměrnost, měřítko, práce, pohyb',
    'D-GRAF': 'Grafy, tabulky, aritmetický průměr',
    'G-UHLY': 'Úhly',
    'G-ROV': 'Obvod a obsah rovinných útvarů',
    'G-PYT': 'Pythagorova věta',
    'G-KRUH': 'Kruh, kružnice, π',
    'G-TEL': 'Tělesa – objem, povrch, sítě',
    'G-KON': 'Konstrukční úlohy',
    'G-SOUM': 'Souměrnost',
    'X-NEST': 'Nestandardní úlohy, zákonitosti',
}
FMT = {'OV': 'otevřená, jen výsledek', 'OP': 'otevřená s postupem',
       'OV+OP': 'otevřená, část s postupem', 'K': 'konstrukční',
       'AN': 'svazek dichotomických (A/N)', 'MC': 'výběr z 5 (A–E)',
       'PR': 'přiřazovací (A–F)'}
TERM = {'A': '1. řádný', 'B': '2. řádný', 'C': '1. náhradní', 'D': '2. náhradní'}

stats = {}
with open(os.path.join(HERE, 'data/m9_item_stats_2022_2026.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f):
        stats[(r['year'], r['term'], r['item'])] = r
ALIAS = {('2023', 'B', '9'): '9.3'}


def subs(task, sp, fmt):
    if sp.startswith('b'):
        return [(f'{task}.{i}', None) for i in (1, 2, 3)], int(sp[1:])
    if ':' not in sp:
        return [(task, int(sp))], int(sp)
    out = [(a, int(b)) for a, b in (x.split(':') for x in sp.split(','))]
    return out, sum(p for _, p in out)


def pct_correct(row, key):
    """share choosing the key option, from the distribution string"""
    d = dict(x.split(':') for x in row['distribution_pct'].split() if ':' in x)
    key = {'Ano': 'A', 'Ne': 'N'}.get(key, key)
    if key in d:
        return float(d[key])
    if key == 'N' and 'B' in d:      # 2024+ files label A/N as columns A, B
        return float(d['B'])
    return None


tasks = []
with open(os.path.join(HERE, 'data/m9_task_catalog.tsv'), encoding='utf-8') as f:
    for r in csv.DictReader(f, delimiter='\t'):
        sl, pts = subs(r['task'], r['subpoints'], r['fmt'])
        keys = r['keys'].split(',') if r['keys'] else []
        vals, skips, w = [], [], []
        closed = r['fmt'] in ('AN', 'MC', 'PR')
        for i, (sid, sp) in enumerate(sl):
            sid = ALIAS.get((r['year'], r['term'], sid), sid)
            s = stats.get((r['year'], r['term'], sid)) or (
                stats.get((r['year'], r['term'], r['task'])) if not closed else None)
            if not s:
                continue
            if closed:
                v = pct_correct(s, keys[i]) if keys else None
            else:
                v = float(s['mean_pct_score']) if s['mean_pct_score'] != '' else None
            if v is not None:
                vals.append(v); w.append(sp or 1)
            if s['skipped_pct'] != '':
                skips.append(float(s['skipped_pct']))
        r['pts'] = pts
        r['succ'] = sum(v * x for v, x in zip(vals, w)) / sum(w) if vals else None
        r['skip'] = sum(skips) / len(skips) if skips else None
        r['taglist'] = r['tags'].split(';')
        tasks.append(r)

# ---- validation
tot = collections.Counter()
for t in tasks:
    tot[(t['year'], t['term'])] += t['pts']
assert all(v == 50 for v in tot.values()), tot
assert len(tot) == 20

out = ['# Katalog úloh M9 2022–2026 (čtyřleté obory)', '',
       'Generated by `analysis/build_catalog.py`. One row per task of each of the 20 official tests in '
       '`References/Matematika/`. Classification (format, topic tags, description) was done by reading the '
       'booklets and keys; the last two columns come from CERMAT\'s published aggregated item results '
       '(`data/m9_item_stats_2022_2026.csv`).', '',
       '- **Úspěšnost** = average % score on the task (open tasks: points earned / max; closed tasks: share '
       'of candidates choosing the keyed answer, averaged over sub-items – for A/N bundles this is *not* the '
       'bundle score, because a bundle gives 4/2/0 points).',
       '- **Vynechalo** = share of candidates who left the task blank.',
       '- No item results are published for 2024 C and D. Replacement terms (C, D) are sat by only a few '
       'hundred candidates, so their percentages are noisy.', '',
       '## Formats', ''] + [f'- `{k}` – {v}' for k, v in FMT.items()] + ['', '## Topic tags', ''] + \
      [f'- `{k}` – {v}' for k, v in TAGS.items()] + ['']
for (y, term) in sorted(tot):
    out += [f'## {y} {term} – {TERM[term]} termín', '',
            '| Úloha | Body | Formát | Témata | Obsah | Úspěšnost | Vynechalo |', '|---|---|---|---|---|---|---|']
    for t in tasks:
        if (t['year'], t['term']) != (y, term):
            continue
        s = f"{t['succ']:.0f} %" if t['succ'] is not None else '–'
        k = f"{t['skip']:.0f} %" if t['skip'] is not None else '–'
        out.append(f"| {t['task']} | {t['pts']} | {t['fmt']} | {', '.join(t['taglist'])} | {t['desc']} | {s} | {k} |")
    out.append('')
open(os.path.join(HERE, '02_katalog_uloh.md'), 'w', encoding='utf-8').write('\n'.join(out))

# ---- summaries (printed; pasted into 01_baseline_M9.md)
STD = [t for t in tasks if t['year'] != '2024']
Y24 = [t for t in tasks if t['year'] == '2024']
REG = [t for t in tasks if t['term'] in 'AB' and t['succ'] is not None]


def by_tag(ts, ntests):
    c = collections.Counter(); n = collections.Counter()
    for t in ts:
        for g in t['taglist']:
            c[g] += t['pts'] / len(t['taglist'])
        for g in set(t['taglist']):
            n[(g, t['year'], t['term'])] = 1
    cnt = collections.Counter(g for g, _, _ in n)
    return [(g, c[g] / ntests, cnt[g]) for g in TAGS]


print('== points per test by tag: standard years (16 tests) vs 2024 (4 tests); tests containing tag')
a = by_tag(STD, 16); b = by_tag(Y24, 4)
for (g, p, n), (_, p2, n2) in zip(a, b):
    print(f'{g:7s} {TAGS[g]:48s} {p:5.1f} b  {n:2d}/16 | {p2:5.1f} b  {n2}/4')

print('\n== success by tag, regular terms A+B (points-weighted), standard years | 2024')
for g in TAGS:
    for name, ys in (('std', ('2022', '2023', '2025', '2026')), ('2024', ('2024',))):
        ts = [t for t in REG if g in t['taglist'] and t['year'] in ys]
        if ts:
            w = sum(t['pts'] for t in ts)
            print(f"{g:7s} {name:5s} n={len(ts):2d} succ={sum(t['succ']*t['pts'] for t in ts)/w:5.1f} "
                  f"skip={sum((t['skip'] or 0)*t['pts'] for t in ts)/w:5.1f}")

print('\n== success by format, regular terms, standard years')
for fm in FMT:
    ts = [t for t in REG if t['fmt'] == fm and t['year'] != '2024']
    if ts:
        w = sum(t['pts'] for t in ts)
        print(f"{fm:6s} n={len(ts):2d} pts/test={w/8:4.1f} succ={sum(t['succ']*t['pts'] for t in ts)/w:5.1f} "
              f"skip={sum((t['skip'] or 0)*t['pts'] for t in ts)/w:5.1f}")

print('\n== success by task number, regular terms, standard years (8 tests)')
for i in range(1, 17):
    ts = [t for t in REG if t['task'] == str(i) and t['year'] != '2024']
    print(f"{i:2d} pts={sum(t['pts'] for t in ts)/len(ts):3.1f} succ={sum(t['succ'] for t in ts)/len(ts):5.1f} "
          f"min={min(t['succ'] for t in ts):4.0f} max={max(t['succ'] for t in ts):4.0f} "
          f"skip={sum(t['skip'] or 0 for t in ts)/len(ts):5.1f} fmts={sorted(set(t['fmt'] for t in ts))}")

print('\n== points by format per test')
for (y, term) in sorted(tot):
    c = collections.Counter()
    for t in tasks:
        if (t['year'], t['term']) == (y, term):
            c[t['fmt']] += t['pts']
    print(y, term, dict(c))

print('\n== sub-item level: last sub-item of task 16 and hardest items, regular terms')
rows = []
for (y, term, item), s in stats.items():
    if term in 'AB' and s['mean_pct_score'] != '' and s['key'] == '' and float(s['mean_pct_score']) < 10:
        rows.append((float(s['mean_pct_score']), y, term, item, s['skipped_pct']))
for r in sorted(rows):
    print(r)
