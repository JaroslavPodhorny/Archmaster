"""PARKED EXPERIMENT (October 2026). Not the curriculum tree the project works on;
that is analysis/data/m9_topic_tree.json. See README.md in this folder.

Trial of a knowledge graph built from solutions. Reads m9_graph_trial.json: nodes in three layers (zaklad, nastroj, typ)
with `requires` links, and items whose solution is written as steps, each step
naming the one node it uses. Validates the file, measures how much the items
share, and writes report.md. A throwaway script: it decides whether the
approach is worth building, it is not the tool.

    uv run --project backend python analysis/parked_graph_trial/graph_trial.py
"""
import collections, json, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYERS = ['zaklad', 'nastroj', 'typ']          # low to high
LAYER_NAME = {'zaklad': 'Základy', 'nastroj': 'Nástroje', 'typ': 'Typy úloh'}


def load(name):
    folder = HERE if name == 'm9_graph_trial.json' else os.path.join(HERE, '..', 'data')
    with open(os.path.join(folder, name), encoding='utf-8') as f:
        return json.load(f)


trial = load('m9_graph_trial.json')
nodes = {n['id']: n for n in trial['nodes']}
items = trial['items']
floor = [n['id'] for n in trial['nodes'] if n.get('floor')]


def closure(ids, requires):
    seen, stack = set(), list(ids)
    while stack:
        i = stack.pop()
        if i not in seen:
            seen.add(i)
            stack.extend(requires(i))
    return seen


def below(ids):
    return closure(ids, lambda i: nodes[i]['requires'])


def label(item):
    return f"{item['test']} {item['item']}"


def validate():
    errors = []
    if len(nodes) != len(trial['nodes']):
        errors.append('duplicate node id')
    for n in nodes.values():
        if n['layer'] not in LAYERS:
            errors.append(f"{n['id']}: unknown layer {n['layer']}")
        for r in n['requires']:
            if r not in nodes:
                errors.append(f"{n['id']}: requires unknown node {r}")
            elif LAYERS.index(nodes[r]['layer']) > LAYERS.index(n['layer']):
                errors.append(f"{n['id']} ({n['layer']}) requires {r} from a higher layer")
    if errors:
        return errors
    state = {}

    def visit(i, path):
        if state.get(i) == 'done':
            return
        if state.get(i) == 'open':
            errors.append('cycle: ' + ' -> '.join(path + [i]))
            return
        state[i] = 'open'
        for r in nodes[i]['requires']:
            visit(r, path + [i])
        state[i] = 'done'
    for i in nodes:
        visit(i, [])
    for it in items:
        for t in it['types']:
            if t not in nodes or nodes[t]['layer'] != 'typ':
                errors.append(f"{label(it)}: type {t} is not a node of the layer typ")
        for text, node in it['steps']:
            if node not in nodes:
                errors.append(f"{label(it)}: step uses unknown node {node}")
        if not any(node in it['types'] for _, node in it['steps']):
            errors.append(f"{label(it)}: no step names its type")
    return errors


errors = validate()
if errors:
    print('\n'.join(errors))
    sys.exit(1)

# ---- what each item uses ---------------------------------------------------
direct = {label(it): [n for _, n in it['steps']] for it in items}
graph = {label(it): below(set(direct[label(it)]) | set(it['types'])) for it in items}
extras = {label(it): sorted(set(direct[label(it)]) - below(it['types'])) for it in items}
sample = [it for it in items if it['group'] == 'sample']
same_type = [it for it in items if it['group'] == 'same-type']

# ---- the old tree, for comparison -----------------------------------------
old_skills = {s['id']: s for a in load('m9_topic_tree.json')['areas']
              for t in a['children'] for s in t['children']}
old_items = load('m9_item_skills.json')


def old_graph(it):
    tags = old_items[it['test']][it['item']]
    return tags, closure(tags, lambda i: old_skills[i].get('requires', []))


def depth(i, memo={}):
    if i not in memo:
        memo[i] = 1 + max((depth(r) for r in nodes[i]['requires']), default=0)
    return memo[i]


def by_layer(ids):
    return {l: sorted(i for i in ids if nodes[i]['layer'] == l) for l in LAYERS}


def names(ids):
    return ', '.join(nodes[i]['name'] for i in ids) or '–'


def mean(xs):
    return sum(xs) / len(xs)


# ---- report ----------------------------------------------------------------
out = []
w = out.append
w('# Trial: knowledge graph built from solutions (M9)\n')
w('Generated by `graph_trial.py` from `m9_graph_trial.json`. Do not edit by hand.\n')
w('**Parked experiment.** This is not the curriculum tree the project works on; see `README.md` in this folder.\n')
w('Each item below was solved from its screenshot and checked against the official key. '
  'The steps, the nodes and the `requires` links are one reader\'s judgement. '
  'The layer of a node (základ / nástroj / typ) is also a judgement and was not checked against the RVP.\n')

w('## Numbers\n')
used_directly = collections.Counter(n for it in items for n in set(direct[label(it)]))
used_sample = collections.Counter(n for it in sample for n in set(direct[label(it)]))
in_graph_sample = collections.Counter(n for it in sample for n in graph[label(it)])
w('| Layer | Nodes | Named by a step | Named by 2+ of the 30 sample items | In the sub-graph of 2+ sample items |')
w('|---|---|---|---|---|')
for l in reversed(LAYERS):
    ids = [i for i in nodes if nodes[i]['layer'] == l]
    w(f"| {LAYER_NAME[l]} | {len(ids)} | {sum(1 for i in ids if used_directly[i])} | "
      f"{sum(1 for i in ids if used_sample[i] >= 2)} | {sum(1 for i in ids if in_graph_sample[i] >= 2)} |")
w(f"| All | {len(nodes)} | {sum(1 for i in nodes if used_directly[i])} | "
  f"{sum(1 for i in nodes if used_sample[i] >= 2)} | {sum(1 for i in nodes if in_graph_sample[i] >= 2)} |\n")

steps = [n for it in items for _, n in it['steps']]
w(f"- {len(items)} items ({len(sample)} sampled one per topic, {len(same_type)} more of one type), "
  f"{len(steps)} steps, {mean([len(it['steps']) for it in items]):.1f} per item.")
w(f"- {sum(1 for n in steps if n in floor)} steps use only the floor node "
  f"({names(floor)}), which is not broken down further.")
w(f"- {sum(1 for i in nodes if not used_directly[i])} nodes are named by no step and exist only as a prerequisite: "
  f"{names(i for i in nodes if not used_directly[i])}.")
w(f"- {sum(len(n['requires']) for n in nodes.values())} `requires` links; the longest chain has "
  f"{max(depth(i) for i in nodes)} nodes.\n")

w('### New nodes per ten items\n')
w('If items share nodes, later items should add fewer new ones. The 30 sample items are taken '
  'in 500 random orders and the counts averaged, so the order of the sample does not matter.\n')
w('| Sample items | New typy | New nástroje | New základy |')
w('|---|---|---|---|')
rng, runs = random.Random(2026), 500
totals = collections.Counter()
for _ in range(runs):
    order, seen = sample[:], set()
    rng.shuffle(order)
    for pos, it in enumerate(order):
        for i in graph[label(it)] - seen:
            totals[pos // 10, nodes[i]['layer']] += 1
        seen |= graph[label(it)]
for block in range(3):
    w(f"| {block * 10 + 1}–{block * 10 + 10} | " + ' | '.join(
        f"{totals[block, l] / runs:.1f}" for l in reversed(LAYERS)) + ' |')
b = by_layer(set().union(*[graph[label(it)] for it in same_type]) - seen)
w(f"| 8 more of one type | {len(b['typ'])} | {len(b['nastroj'])} | {len(b['zaklad'])} |\n")
w(f"- {sum(1 for it in items if extras[label(it)])} of {len(items)} items have a step whose node "
  f"their type does not require ({mean([len(extras[label(it)]) for it in items]):.1f} such nodes per item).\n")

w('### Size of an item\'s sub-graph: old tree and trial\n')
old_sizes = [len(old_graph(it)[1]) for it in items]
old_tags = [len(old_graph(it)[0]) for it in items]
new_sizes = [len(graph[label(it)]) for it in items]
new_direct = [len(set(direct[label(it)])) for it in items]
w('| | Named directly, mean | Sub-graph, mean | Sub-graph, min–max |')
w('|---|---|---|---|')
w(f"| Old tree (`m9_item_skills.json`) | {mean(old_tags):.1f} | {mean(old_sizes):.1f} | {min(old_sizes)}–{max(old_sizes)} |")
w(f"| Trial | {mean(new_direct):.1f} | {mean(new_sizes):.1f} | {min(new_sizes)}–{max(new_sizes)} |\n")

w('### Types with more than one item\n')
w('What the items of one type share (named by all of them) and what only some of them need.\n')
w('| Type | Items | Named by all | Named by some |')
w('|---|---|---|---|')
by_type = collections.defaultdict(list)
for it in items:
    for t in it['types']:
        by_type[t].append(it)
for t, its in by_type.items():
    if len(its) > 1:
        sets = [set(direct[label(it)]) - {t} for it in its]
        common = set.intersection(*sets)
        some = collections.Counter(n for s in sets for n in s - common)
        w(f"| {nodes[t]['name']} | {len(its)} | {names(sorted(common))} | "
          f"{', '.join(f'{nodes[n]['name']} ({c})' for n, c in some.most_common()) or '–'} |")
w('')

w('### Nodes most items rest on\n')
w('| Node | Layer | Named by items | In the sub-graph of items |')
w('|---|---|---|---|')
in_graph = collections.Counter(n for it in items for n in graph[label(it)])
for i, c in in_graph.most_common(15):
    w(f"| {nodes[i]['name']} | {LAYER_NAME[nodes[i]['layer']]} | {used_directly[i]} | {c} |")
w('')

w('## Items\n')
for it in items:
    year, term = it['test'].split()
    task = it['item'].split('.')[0]
    pid = f"M9-{year}-{term}-{int(task):02d}"
    w(f"### {label(it)} — {names(it['types'])}\n")
    w(f"[zadání](../../backend/data/screenshots/{pid}.png) · "
      f"[klíč](../../backend/data/screenshots/{pid}-reseni.png) · výsledek: {it['answer']}\n")
    w('| Krok | Uzel |')
    w('|---|---|')
    for text, node in it['steps']:
        w(f"| {text.replace('|', '∣')} | {nodes[node]['name']} |")
    w('')
    rest = by_layer(graph[label(it)] - set(direct[label(it)]) - set(it['types']))
    w(f"- Pod tím: {names(rest['nastroj'] + rest['zaklad'])}")
    w(f"- Navíc k typu (krok, který typ sám nevyžaduje): {names(extras[label(it)])}")
    tags, old = old_graph(it)
    w(f"- Starý strom: {', '.join(tags)}. Velikost podgrafu: starý {len(old)}, nový {len(graph[label(it)])}.\n")

w('## Nodes\n')
for l in reversed(LAYERS):
    w(f"### {LAYER_NAME[l]}\n")
    w('| Uzel | Vyžaduje | Kroky |')
    w('|---|---|---|')
    for n in trial['nodes']:
        if n['layer'] == l:
            w(f"| {n['name']} | {names(n['requires'])} | {steps.count(n['id'])} |")
    w('')

path = os.path.join(HERE, 'report.md')
with open(path, 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))
print('\n'.join(out[:out.index('## Items\n')]))
print(f'wrote {path}')
